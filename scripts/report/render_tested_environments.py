"""Render the installation table from docs/data/tested_environments.json.

Run from any directory; --check exits nonzero if the committed table is stale.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/data/tested_environments.json"
DESTINATION = ROOT / "docs/getting_started/tested_environments_table.rst.inc"


def test_result(result: dict | None) -> str:
    if not result:
        return "Not re-tested"
    if "passed" not in result:
        return "Blocked" if result.get("exit_code") else "Not run"
    counts = ", ".join(
        f"{result.get(key, 0)} {label}"
        for key, label in (("passed", "passed"), ("failures", "failed"),
                           ("errors", "errors"), ("skipped", "skipped"))
    )
    return f"{counts}; {result['runtime_seconds']:.1f} s"


def render(data: dict) -> str:
    lines = [
        ".. Generated by scripts/report/render_tested_environments.py; do not edit.",
        "", ".. list-table:: Tested environments", "   :header-rows: 1", "",
    ]
    rows = [["Environment / GPU", "Python", "PyTorch / CUDA wheel",
             "torch-scatter / PyG", "CPU contracts", "GPU smoke", "Evidence"]]
    for record in data["environments"]:
        rows.append([
            f"{record['name']} ({record.get('gpu') or 'CPU'})",
            record["python"],
            f"{record['torch']} / {record.get('cuda_wheel_tag') or 'not recorded'}",
            f"{record.get('torch_scatter') or 'not recorded'} / "
            f"{record.get('torch_geometric') or 'not recorded'}",
            test_result(record.get("cpu_tests")),
            test_result(record.get("gpu_smoke")),
            f"{record['status']}" + (f", {record['date']}" if record.get("date") else "")
            + (f"; {record['table_note']}" if record.get("table_note") else ""),
        ])
    for row in rows:
        lines.append(f"   * - {row[0]}")
        lines.extend(f"     - {cell}" for cell in row[1:])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != output:
            parser.exit(1, f"Stale table: run python {Path(__file__).relative_to(ROOT)}\n")
    else:
        DESTINATION.write_text(output)


if __name__ == "__main__":
    main()
