"""Render the list of working setups from docs/data/tested_environments.json.

Run from any directory; --check exits nonzero if the committed table is stale.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/data/tested_environments.json"
DESTINATION = ROOT / "docs/getting_started/tested_environments_table.rst.inc"


def working(record: dict) -> bool:
    """A setup counts when it ran the model on a GPU, or is a reported working host."""
    if record.get("status") == "reported":
        return "patch" not in str(record.get("torch", ""))
    smoke = record.get("gpu_smoke") or {}
    return (
        bool(smoke.get("passed"))
        and not smoke.get("failures")
        and not smoke.get("errors")
    )


def _cuda(record: dict) -> str:
    tag = record.get("cuda_wheel_tag") or ""
    if tag == "cpu" or "+cpu" in str(record.get("torch", "")):
        return "CPU"
    if tag.startswith("cu") and len(tag) >= 5:
        return f"{tag[2:-1]}.{tag[-1]}"
    return tag or "not recorded"


def _driver(record: dict) -> str:
    driver = record.get("driver") or "not recorded"
    compat = record.get("cuda_compat") or record.get("compat_driver")
    if compat:
        driver = f"{driver} with cuda-compat {compat}"
    elif _cuda(record).startswith("13.") and driver != "not recorded":
        driver = f"{driver} with NVIDIA cuda-compat libraries"
    return driver


def render(data: dict) -> str:
    rows = []
    seen = set()
    for record in data["environments"]:
        if not working(record):
            continue
        torch_version = str(record["torch"]).split("+")[0]
        python = ".".join(str(record["python"]).split(".")[:2])
        key = (python, torch_version, _cuda(record))
        row = (
            *key,
            str(record.get("torch_scatter") or "\u2014").split("+")[0],
            str(record.get("torch_geometric") or "\u2014"),
            _driver(record) if record.get("driver") else "\u2014",
        )
        if key in seen:
            # Keep the row with recorded versions over a bare report.
            if "\u2014" not in row:
                rows[[r[:3] for r in rows].index(key)] = row
            continue
        seen.add(key)
        rows.append(row)
    rows.sort(key=lambda r: (tuple(int(x) for x in r[0].split(".")), r[1], r[2]))
    lines = [
        ".. Generated by scripts/report/render_tested_environments.py; do not edit.",
        "",
        ".. list-table:: Working setups",
        "   :header-rows: 1",
        "",
        "   * - Python",
        "     - PyTorch",
        "     - CUDA",
        "     - torch-scatter",
        "     - torch_geometric",
        "     - NVIDIA driver",
    ]
    for row in rows:
        lines.append(f"   * - {row[0]}")
        lines.extend(f"     - {cell}" for cell in row[1:])
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != output:
            parser.exit(
                1, f"Stale table: run python {Path(__file__).relative_to(ROOT)}\n"
            )
    else:
        DESTINATION.write_text(output)


if __name__ == "__main__":
    main()
